/*
 * embed: turn files into a C table of named byte arrays (build helper for
 * xfd-native). Used for the slaves in m68k/extra, which are built in.
 * Usage: embed OUTPUT.c FILE...
 * Emits `const struct xfd_embedded xfd_embedded_slaves[]` (name, data, size)
 * and `const size_t xfd_embedded_slaves_count`. The name is the file's
 * basename.
 *
 * Copyright (C) 2026 the xfd-native authors.
 * SPDX-License-Identifier: LGPL-2.1-or-later
 */
#include <stdio.h>
#include <string.h>

static const char *basename_of(const char *path)
{
	const char *b = path;
	for (const char *p = path; *p; p++) {
		if (*p == '/' || *p == '\\') b = p + 1;
	}
	return b;
}

int main(int argc, char **argv)
{
	FILE *out;
	int i, c;

	if (argc < 2) {
		fputs("usage: embed OUTPUT.c FILE...\n", stderr);
		return 2;
	}
	out = fopen(argv[1], "w");
	if (!out) {
		perror(argv[1]);
		return 1;
	}
	fputs("/* Generated by tools/embed. Do not edit. */\n#include <stddef.h>\n\n"
	      "struct xfd_embedded { const char *name; const unsigned char *data; size_t size; };\n\n",
	      out);
	for (i = 2; i < argc; i++) {
		FILE *in = fopen(argv[i], "rb");
		unsigned long n = 0;
		if (!in) {
			perror(argv[i]);
			fclose(out);
			return 1;
		}
		fprintf(out, "static const unsigned char embedded_%d[] = {", i - 2);
		while ((c = fgetc(in)) != EOF) {
			fprintf(out, "%s0x%02x,", (n % 16) ? " " : "\n\t", c);
			n++;
		}
		fclose(in);
		if (n == 0) fputs("0", out);
		fprintf(out, "\n}; /* %s, %lu bytes */\n\n", argv[i], n);
	}
	fputs("const struct xfd_embedded xfd_embedded_slaves[] = {\n", out);
	for (i = 2; i < argc; i++) {
		fprintf(out, "\t{\"%s\", embedded_%d, sizeof(embedded_%d)},\n", basename_of(argv[i]), i - 2, i - 2);
	}
	if (argc == 2) fputs("\t{NULL, NULL, 0},\n", out);
	fprintf(out, "};\nconst size_t xfd_embedded_slaves_count = %d;\n", argc - 2);
	if (fclose(out) != 0) {
		perror(argv[1]);
		return 1;
	}
	return 0;
}
